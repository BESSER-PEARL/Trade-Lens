"""InsightsGenerator: a BESSER generator that adds analytics endpoints
(significance rankings, ladders, series with seasonal adjustment, movers,
peer comparison and specialisation) to a backend generated by BESSER's
BackendGenerator or WebAppGenerator.
"""
from __future__ import annotations

import json
import os
import re
from pathlib import Path
from typing import Optional

from jinja2 import Environment, FileSystemLoader

from besser.BUML.metamodel.structural import DomainModel
from besser.generators import GeneratorInterface

from ...importer.sdmx_to_buml import ImportMapping

TEMPLATES = Path(__file__).parent / "templates"


class InsightsGenerator(GeneratorInterface):
    """Generate ``routers/insights.py`` and register it in ``main_api.py``.

    Everything is derived from the dimension roles stored in the import mapping (see
    ``besser_sdmx.importer.roles``); every argument below only overrides that.

    Args:
        model: the domain model the backend was generated from.
        mapping: the SDMX import mapping (which classes/attributes hold which dimension, and their roles).
        output_dir: the generated backend folder (the one containing ``main_api.py``).
        title: human-readable dataset title (default: the dataflow name).
        defaults: code per dimension used when a query does not filter it (default: each
            dimension's ``default_code``: its total, or the headline unit). Avoids double counting.
        totals: the code holding each dimension's total (default: detected ``total_code``).
        member_patterns: regex matching the "real" items of a dimension (default: ISO countries
            for geographic dimensions), so aggregates such as EU27 are left out of rankings.
        labels: display names per dimension id (default: the SDMX concept names).
        base_threshold: significance threshold at the first level (0.01 = 1%); each level
            of a hierarchy divides it by ten (the significance ladder).
        comparison: ``{"dimension": "reporter", "peers": [...] | "auto"}`` for specialisation
            (default: the focused geographic dimension against every other country in the data).
        focus: codes the whole app is about, e.g. ``{"reporter": "LU"}``.
    """

    def __init__(
        self,
        model: DomainModel,
        mapping: ImportMapping,
        output_dir: str,
        title: str = "",
        defaults: Optional[dict[str, str]] = None,
        totals: Optional[dict[str, str]] = None,
        member_patterns: Optional[dict[str, str]] = None,
        labels: Optional[dict[str, str]] = None,
        base_threshold: float = 0.01,
        comparison: Optional[dict] = None,
        frequency_dimension: Optional[str] = None,
        focus: Optional[dict[str, str]] = None,
    ):
        super().__init__(model, output_dir)
        self.mapping = mapping
        self.title = title or mapping.title or model.name
        self.defaults = defaults or {}
        self.totals = totals or {}
        self.member_patterns = member_patterns or {}
        self.labels = labels or {}
        self.base_threshold = base_threshold
        self.comparison = comparison
        self.frequency_dimension = frequency_dimension
        self.focus = focus or {}

    def config(self) -> dict:
        from ...importer.roles import GEO_MEMBER_PATTERN

        m = self.mapping
        dims = []
        defaults: dict[str, str] = {}
        for d in m.dimensions:
            entry = {
                "id": d.id,
                "label": self.labels.get(d.id) or d.label or d.id.replace("_", " ").capitalize(),
                "kind": d.kind,
                "role": d.role,
                "column": f"{d.attr}_id" if d.kind == "class" else d.attr,
                "table": d.type_name.lower() if d.kind == "class" else None,
                "parent_column": "parent_id" if d.hierarchy else None,
                "hierarchy": d.hierarchy,
                "literals": d.literals,
                "total_code": self.totals.get(d.id, d.total_code),
                "member_pattern": self.member_patterns.get(d.id, GEO_MEMBER_PATTERN if d.role == "geo" else None),
            }
            dims.append(entry)
            if d.default_code is not None:
                defaults[d.id] = d.default_code
        defaults.update(self.defaults)
        time_id = m.time_attr or "time_period"
        dims.append({"id": time_id, "label": "Period", "kind": "time", "role": "time", "column": m.time_attr,
                     "table": None, "parent_column": None, "hierarchy": None, "literals": {}, "total_code": None,
                     "member_pattern": None})
        freq = self.frequency_dimension or next((d.id for d in m.dimensions if d.role == "frequency"), None) or next(
            (d.id for d in m.dimensions if d.id.lower() in ("freq", "frequency") and d.kind == "enum"), None)
        comparison = self.comparison
        sdmx = None  # where the router fetches slices that were never loaded (lazy live fetch)
        if m.source:
            from ...importer.client import SOURCES

            src = SOURCES.get(m.source)
            if src is not None:
                sdmx = {"source": m.source, "name": src.name, "base_url": src.base_url, "agency": src.agency,
                        "flow": m.dataflow, "dimensions": [d.id for d in m.dimensions],
                        "attributes": dict(m.attributes), "timeout": 20}
        unit_mult = next((col for sid, col in m.attributes.items() if sid.upper() == "UNIT_MULT"), None)
        if comparison is None:
            geo_focus = next((d.id for d in m.dimensions if d.role == "geo" and d.id in self.focus), None)
            if geo_focus:
                comparison = {"dimension": geo_focus, "peers": "auto"}
        return {
            "title": self.title,
            "dataflow": m.dataflow,
            "source": m.source,
            "observation_table": m.observation_class.lower(),
            "time_column": m.time_attr,
            "time_dimension": time_id,
            "value_column": m.value_attr,
            "frequency_dimension": freq,
            "dimensions": dims,
            "defaults": defaults,
            "focus": self.focus,
            "base_threshold": self.base_threshold,
            "comparison": comparison,
            "sdmx": sdmx,
            "unit_mult_column": unit_mult,
            "code_labels": {d.id: d.code_labels for d in m.dimensions if getattr(d, "code_labels", None)},
        }

    def generate(self) -> str:
        env = Environment(loader=FileSystemLoader(str(TEMPLATES)), keep_trailing_newline=True)
        code = env.get_template("insights_router.py.j2").render(
            model_name=self.model.name,
            config_json=json.dumps(self.config(), indent=2, ensure_ascii=False),
        )
        backend = Path(self.build_generation_dir())
        routers = backend / "routers"
        routers.mkdir(parents=True, exist_ok=True)
        target = routers / "insights.py"
        target.write_text(code, encoding="utf-8", newline="\n")
        self._register(backend / "main_api.py")
        self._requirements(backend / "requirements.txt")
        return str(target)

    @staticmethod
    def _requirements(path: Path) -> None:
        """The router fetches missing slices with requests and adjusts series with statsmodels."""
        if not path.exists():
            return
        lines = path.read_text(encoding="utf-8").splitlines()
        names = {re.split(r"[<>=!~\[ ]", ln.strip(), maxsplit=1)[0].lower() for ln in lines if ln.strip()}
        extra = [req for req in ("requests>=2.31.0", "pandas>=2.0.0", "statsmodels>=0.14.0")
                 if req.split(">=")[0] not in names]
        if extra:
            path.write_text("\n".join(lines + extra) + "\n", encoding="utf-8", newline="\n")

    @staticmethod
    def _register(main_api: Path) -> None:
        """Import and include the insights router in the generated FastAPI app (idempotent)."""
        if not main_api.exists():
            return
        src = main_api.read_text(encoding="utf-8")
        if "insights_router" in src:
            return
        imports = list(re.finditer(r"^from routers import \w+ as \w+_router\n", src, re.M))
        includes = list(re.finditer(r"^app\.include_router\(\w+_router\.router\)\n", src, re.M))
        if not imports or not includes:
            raise RuntimeError(f"Could not find router registration in {main_api}")
        # Insert the include first (later in the file), then the import.
        pos = includes[-1].end()
        src = src[:pos] + "app.include_router(insights_router.router)\n" + src[pos:]
        pos = imports[-1].end()
        src = src[:pos] + "from routers import insights as insights_router\n" + src[pos:]
        main_api.write_text(src, encoding="utf-8", newline="\n")

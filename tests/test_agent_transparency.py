    m = methods.method_of("/trends/analyze?flow=EXPORT&freq=M", cat)
    assert m["plain"] == "Takes the ups and downs out." and m["params"] == {"flow": "EXPORT", "freq": "M"}
    assert methods.plain_method_words("The PELT algorithm found four breaks after an STL decomposition.") == \
        "The change-point analysis found four breaks after a seasonal adjustment."
    assert "Movers" in methods.prompt_lines() and "/insights" not in methods.prompt_lines()
    assert plain_words("From /trends/analyze?flow=EXPORT.") == \
        "From Eurostat trade data (ds-045409); change-point analysis of the monthly series."



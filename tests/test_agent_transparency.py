def test_process_talk_never_reaches_the_reader():
    for s in ("I could not redraw the chart because existing notes on it prevented the update.",
              "The notes on it blocked the change.", "The agent slots are full."):
        assert LEAK_RE.search(s), s
    text = "**Visualizer.** Steel goes to Germany. I could not redraw the chart because existing notes on it " \
           "prevented the update.\n\n_Next: Where do the goods go?_"
    assert leaked(text) == ["I could not redraw the chart because existing notes on it prevented the update."]
    assert not LEAK_RE.search("Exports rose by a quarter, mostly smartphones sold to France.")


def test_the_forecast_is_left_to_the_forecaster():
    text = ("**Trend finder.** Exports rose €1.29 bn in 2025 [1]. Smartphones made most of it. Exports will likely "
            "keep rising next year.\n\n_Next: What should we expect for 2026?_")
    out = others_part(text, "trend_finder", ["forecaster"])
    assert "next year" not in out and "Smartphones made most of it." in out
    assert others_part(text, "trend_finder", ["cause_finder"]) == text        # no forecaster in the plan
    assert others_part(text, "forecaster", ["cause_finder"]) == text
    fc = ("**Forecaster.** Exports rose +8.6% in 2025, from €15 bn to €16.3 bn. Electrical machinery was the largest "
          "contributor (+€846 m).\n\nFor 2026, the forecast is €17.3 bn. In the rolling backtest it beat the seasonal "
          "naive forecast by 49.2% one month ahead. I drew the 2026 export band [1].")
    left = others_part(fc, "forecaster", ["trend_finder"])                     # the past change is the trend finder's
    assert "rose +8.6%" not in left and "contributor" not in left and "For 2026" in left and "[1]" in left
    assert others_part(fc, "forecaster", []) == fc
    nxt = fix_next(out, "trend_finder", ["Why did exports jump in 2025?"], others=["forecaster"])
    assert "expect" not in nxt.split("_Next:")[1].lower()



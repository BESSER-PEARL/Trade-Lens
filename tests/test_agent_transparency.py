@needs_recording
def test_each_reply_carries_its_decision_record(world):
    api, store, boxes = world
    methods.reset()
    q = "Why did exports jump in 2025, and what comes next?"
    plan = json.dumps({"plan": [{"agent": "trend_finder", "task": "Explain the 2025 rise of exports."},
                                {"agent": "forecaster", "task": "What to expect for exports in 2026."}]})
    llm = ScriptedLLM(scripts={
        "trend_finder": [[("drill_down", {"flow": "EXPORT", "period": "2025", "previous": "2024"})],
                         [("add_thread", {"in_code": "CN", "out_code": "FR", "product": "85171300",
                                          "label": "Smartphones", "note": "{bought} in."})],
                         "Exports rose €9.99 bn.",                                    # sent back once
                         "Exports rose €1.29 bn (+8.6%) [1]. Smartphones made most of it. Exports will likely keep "
                         "rising next year.\n\n_Next: What should we expect for 2026?_"],
        "forecaster": [[("add_forecast_band", {"flow": "EXPORT", "note": "Next year: {value}."})],
                       "A band, not a promise."]})
    c = Conversation("replay:", llm, boxes=boxes, router_llm=ScriptedLLM(plans={q: plan}))
    replies = list(c.answer(q))
    tf, fc = replies
    assert "next year" not in tf.text and "expect" not in tf.text.lower()            # the forecaster's part
    assert "forecaster answers what comes next" in llm.prompts["trend_finder"][0]
    assert "trend finder explains what changed" in llm.prompts["forecaster"][0]       # and the other way round
    boxes["forecaster"].others = ["trend_finder"]
    refused = call(boxes["forecaster"], "show_panel", type="waterfall", title="The change", by="product")
    assert refused["ok"] is False and "trend finder draws the change" in refused["error"]
    boxes["forecaster"].others = []
    rec = tf.record
    assert rec["type"] == "what_happened" and rec["version"] == 1 and rec["agent"] == "trend_finder"
    assert rec["question"] == q and rec["agent_title"] == "Trend finder"
    assert list(rec)[:6] == ["type", "version", "agent", "agent_title", "question", "summary"]  # plain words first
    assert rec["summary"].startswith("The trend finder (what changed, down to the product line, and lasting shifts) ran ")
    assert "against the calculations" in rec["summary"]
    assert [s["agent"] for s in rec["plan"]["steps"]] == ["trend_finder", "forecaster"]
    assert rec["plan"]["steps"][0]["this_one"] and not rec["plan"]["steps"][1]["this_one"]
    assert rec["plan"]["steps"][0]["asked"] == "Explain the 2025 rise of exports."
    assert "router" in rec["plan"]["how"]
    names = {c_["name"] for c_ in rec["calculations"]}
    assert "Movers" in names and all(c_["url"].startswith("/") for c_ in rec["calculations"])
    movers = next(m for m in rec["methods"] if m["name"] == "Movers")       # each method once, with its sentence
    assert movers["count"] >= 1 and set(movers) >= {"name", "plain", "count"}
    assert sum(m["count"] for m in rec["methods"]) == len(rec["calculations"])
    first = next(c_ for c_ in rec["calculations"] if c_["name"] == "Movers")
    assert first["about"].startswith("exports by product, 2024 to 2025")
    assert not any("/insights" in c_["name"] for c_ in rec["calculations"])
    mark = next(d for d in rec["drawn"] if d["what"] == "mark")
    assert mark == {**mark, "kind": "thread", "mark": "thread", "on": "crossroads"}
    assert mark["number"] in tf.numbers and mark["number"] in (1, 2)   # the forecaster draws at the same time
    assert mark["method"] and "/" not in mark["method"]
    chk = rec["checked"]
    assert chk["in_reply"] == 2 and chk["verified"] == 2 and chk["unmatched"] == 0 and chk["corrected"] == 1
    assert "checked against the calculations" in chk["words"] and "sent back" in chk["words"]
    assert rec["time"]["seconds"] >= 0 and rec["time"]["since_question"] is not None
    assert rec["for_statisticians"]["queries"] == [c_["url"] for c_ in rec["calculations"]]
    assert "drill_down" not in json.dumps({k: v for k, v in rec.items() if k != "for_statisticians"})
    assert fc.record["agent"] == "forecaster"
    assert any(d["what"] == "mark" and d["kind"] == "forecast" for d in fc.record["drawn"])
    assert any(c_["name"] == "Forecast with its test" for c_ in fc.record["calculations"])
    json.dumps(rec)   # the page gets it as JSON


def _fake_baf(monkeypatch):
    """BAF's message and payload classes, as far as reply_with_record uses them (BAF lives in .venv-agent)."""
    import enum
    import types
    from datetime import datetime

    class MessageType(enum.Enum):
        STR = "str"

    class Message:
        def __init__(self, t, content, is_user, timestamp):
            self.t, self.content, self.is_user, self.timestamp = t, content, is_user, timestamp

    class PayloadAction(enum.Enum):
        AGENT_REPLY_STR = "agent_reply_str"

    class Payload:
        def __init__(self, action, message=None, history=False, timestamp=None, message_id=None):
            self.action, self.message, self.history, self.timestamp = action.value, message, history, timestamp
            self.message_id = message_id

    class PayloadEncoder(json.JSONEncoder):
        def default(self, obj):
            if isinstance(obj, Payload):
                return {"action": obj.action, "message": obj.message, "history": obj.history,
                        "timestamp": obj.timestamp.strftime("%Y-%m-%d %H:%M:%S") if obj.timestamp else None,
                        "message_id": obj.message_id}
            return super().default(obj)

    msg = types.ModuleType("baf.core.message")
    msg.Message, msg.MessageType = Message, MessageType
    pay = types.ModuleType("baf.platforms.payload")
    pay.Payload, pay.PayloadAction, pay.PayloadEncoder = Payload, PayloadAction, PayloadEncoder
    for name in ("baf", "baf.core", "baf.platforms"):
        if name not in sys.modules:
            monkeypatch.setitem(sys.modules, name, types.ModuleType(name))
    if "baf.core.message" not in sys.modules or not hasattr(sys.modules["baf.core.message"], "Message"):
        monkeypatch.setitem(sys.modules, "baf.core.message", msg)
    if "baf.platforms.payload" not in sys.modules or not hasattr(sys.modules["baf.platforms.payload"], "Payload"):
        monkeypatch.setitem(sys.modules, "baf.platforms.payload", pay)
    assert datetime


def test_the_record_goes_with_the_reply_in_one_message(monkeypatch):
    from lux_insights import lux_insights_agent as agent_mod
    _fake_baf(monkeypatch)
    sent = []

    class Conn:
        def send(self, s):
            sent.append(json.loads(s))

    class FakeAgent:
        def process(self, session, message, is_user_message):
            return message

    class Platform:
        _connections = {"s1": Conn()}
        _agent = FakeAgent()

    class Session:
        id = "s1"
        platform = Platform()
        saved = []

        def save_message(self, m):
            self.saved.append(m)

        def reply(self, text):
            sent.append({"action": "agent_reply_str", "message": text, "plain": True})

    rec = {"type": "what_happened", "agent": "trend_finder", "summary": "ran 2 calculations"}
    agent_mod.reply_with_record(Session(), "**Trend finder.** Exports rose [1].", rec)
    assert sent[-1]["action"] == "agent_reply_str" and sent[-1]["message"] == "**Trend finder.** Exports rose [1]."
    assert sent[-1]["what_happened"] == rec and sent[-1]["agent"] == "trend_finder"
    agent_mod.reply_with_record(Session(), "plain", None)          # no record: BAF's own reply
    assert sent[-1] == {"action": "agent_reply_str", "message": "plain", "plain": True}



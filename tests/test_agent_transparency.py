BACKEND = Path(__file__).resolve().parents[1] / "app" / "backend"


def _empty(store) -> None:
    """The user removes every chart on the page."""
    ops = [{"op": "remove_panel", "id": p["id"], "force": True} for p in store.spec["panels"]]
    store.post_ops({"agent": {"name": "user"}, "ops": ops})
    assert store.spec["panels"] == []



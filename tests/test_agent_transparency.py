@needs_recording
def test_the_agents_build_a_page_from_nothing(world):
    api, store, boxes = world
    _empty(store)
    text = page.summary(store.spec)
    assert "the page is EMPTY" in text and "crossroads and the three figures" not in text
    # 'Show me 2020' on an empty page: a new chart of the year's partners, not a highlight on a missing crossroads
    p = router.route("Show me 2020", None, text, store.spec)
    assert p.source == "rule" and "crossroads is not on the page" in p.steps[0].task
    assert "butterfly" in p.steps[0].task

    tf = boxes["trend_finder"]
    tf.begin("Why did exports jump in 2025?")
    thread = call(tf, "add_thread", in_code="CN", out_code="FR", product="85171300", label="Smartphones")
    assert thread["ok"], thread
    assert [p_["id"] for p_ in store.spec["panels"]] == ["routes"]                 # the first chart is at the top
    assert store.spec["marks"][0]["target"] == "routes" and store.spec["marks"][0]["kind"] == "thread"
    assert "map of partners" in thread["drawn_on"]
    head = call(tf, "write_headline", text="Exports rose {growth} in 2025.", flow="EXPORT", period="2025",
                previous="2024")
    assert head["ok"], head
    assert store.spec["layout"]["rows"][0]["panels"] == ["headline"]              # the headline comes back on top
    fc = boxes["forecaster"]
    fc.begin("What should we expect for 2026?")
    band = call(fc, "add_forecast_band", flow="EXPORT", note="Exports in 2026: {value}.")
    assert band["ok"], band
    target = next(m for m in store.spec["marks"] if m["kind"] == "forecast")["target"]
    assert page.panel(store.spec, target)["type"] == "line" and target == "history"
    # a mark asked for on a chart the user removed: a plain way out, never a raw 'no panel'
    vz = boxes["visualizer"]
    vz.begin("Highlight Germany")
    out = call(vz, "highlight", target="crossroads", note="Germany {de_share}", codes=["DE"])
    assert out["ok"] is False and "the user removed it" in out["error"]

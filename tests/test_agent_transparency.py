def test_the_agents_names_are_the_backends():
    sys.path.insert(0, str(BACKEND))
    try:
        from routers.insights import METHODS
    except Exception as exc:  # the backend's dependencies are not installed here
        pytest.skip(f"backend not importable: {exc}")
    finally:
        sys.path.remove(str(BACKEND))
        for name in list(sys.modules):   # the backend's modules are imported afresh by the backend's own tests
            if name.split(".")[0] in ("main_api", "database", "sql_alchemy", "pydantic_classes", "bal_stdlib",
                                      "routers", "view", "forecasting", "trends"):
                sys.modules.pop(name, None)
    assert set(methods.NAMES) == set(METHODS)
    assert {e: m["name"] for e, m in METHODS.items()} == methods.NAMES
    for endpoint, param, value, name in methods.VARIANT_NAMES:
        assert any(v["name"] == name and str(v["when"].get(param)) == value for v in METHODS[endpoint]["variants"])


def test_a_calculation_is_said_in_plain_words():
    movers = {"by": "product", "period": "2025", "previous": "2024", "flow": "EXPORT", "parent": "85"}
    assert record.about("/insights/movers", movers) == "exports by product, 2024 to 2025, inside electrical machinery"
    ranking = {"by": "partner", "period": "2025", "flow": "IMPORT", "product": "85171300"}
    assert record.about("/insights/ranking", ranking, {"85171300": "Smartphones"}) == \
        "imports by partner country, 2025, smartphones"
    series = {"flow": "EXPORT", "freq": "M", "start": "1999-01", "adjust": "true", "partner": "DE"}
    assert record.about("/insights/series", series) == "monthly exports, from 1999-01, with Germany, seasonally adjusted"
    forecast = {"flow": "EXPORT", "horizon": "12", "method": "nn"}
    assert record.about("/insights/forecast", forecast) == \
        "exports, 12 months ahead, by the neural network generated by BESSER"


def test_a_query_is_named_by_its_method():
    assert methods.method_of("/insights/movers?by=product&period=2025&previous=2024")["name"] == "Movers"
    assert methods.method_of("/insights/series?flow=EXPORT&freq=M&adjust=true")["name"] == "Seasonal adjustment"
    assert methods.method_of("/insights/matrix?by=partner&measure=rank")["name"] == "Ranks over the years"

"""The agent shows its method (app/agents/lux_insights: record.py, methods.py) and copes with a page the user emptied.

- Each specialist's reply carries a decision record ("what_happened"): the plan, the calculations run by their plain
  names from the method catalogue, what was drawn, the figures checked, the time taken.
- Replies name methods in plain words, never leak how the page works inside, leave the forecast to the forecaster
  when it is in the plan, and a chart's title says what the chart shows.
- On an empty page (every panel removed by the user) the agents build the answer from nothing.

Same harness as tests/test_lux_insights_agent.py: recorded /insights answers, the kit's in-memory page, a
scripted LLM.
"""

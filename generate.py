"""Generate the Luxembourg Trade Explorer from its models, into build/generated/.

    python generate.py                 # -> build/generated/ (frontend + backend), not committed
    python generate.py --out DIR       # anywhere else outside app/
    python generate.py --out app --force   # overwrite the maintained app/ (you lose the hand edits)

app/ was generated by BESSER v8.1.0 (+ patches/besser/) from these models at commit cea06c4 and is
now maintained by hand: the agent-driven page (the view spec, /view, the crossroads, the "Ask the
data" panel, the new /insights endpoints) lives only in app/. So this script no longer writes there
by default; it is kept to show, and to check in CI, that the models still generate a working app.

Pipeline:
  model/lux_trade_model.py   B-UML domain model, imported from the SDMX structure
                             of Eurostat ds-045409 (python -m besser_sdmx import ...)
  model/lux_trade_gui.py     B-UML GUI model: the dashboard screens and charts
  BESSER WebAppGenerator     -> React frontend + FastAPI/SQLAlchemy backend
  InsightsGenerator          -> analytics endpoints (significance ladder, series, RCA)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "model"))

APP = ROOT / "app"
OUT = ROOT / "build" / "generated"
FOCUS = {"reporter": "LU"}

REFUSE = """Refusing to write into {out}.

app/ is maintained by hand since commit cea06c4: the agent-driven page, the /view backend and the
new /insights endpoints exist only there, and regenerating would delete them. Generate into
build/generated/ (the default) and compare, or pass --force if you really mean to overwrite app/."""


def _inside(path: Path, folder: Path) -> bool:
    return path == folder or folder in path.parents


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Generate the Luxembourg Trade Explorer from its models")
    parser.add_argument("--out", default=str(OUT), help="output folder (default: build/generated/)")
    parser.add_argument("--force", action="store_true", help="allow writing into app/ (overwrites the hand edits)")
    args = parser.parse_args()
    out = Path(args.out).resolve()
    if _inside(out, APP.resolve()) and not args.force:
        sys.exit(REFUSE.format(out=out))

    # Imported here so that --help and the refusal work without BESSER installed.
    from besser.generators.web_app import WebAppGenerator

    from besser_sdmx.generators import InsightsGenerator
    from besser_sdmx.importer import ImportMapping
    from besser_sdmx.patches import patch_generated_backend
    from lux_trade_gui import build_gui_model
    from lux_trade_model import domain_model

    meta = json.loads((ROOT / "model" / "lux_trade_mapping.json").read_text(encoding="utf-8"))
    mapping = ImportMapping.from_dict(meta["mapping"])
    # The years the app shows: the annual span of the data recipe (model/lux_trade_slices.json).
    recipe = json.loads((ROOT / "model" / "lux_trade_slices.json").read_text(encoding="utf-8"))["slices"]
    annual = [s for s in recipe if s["key"].get("freq") == "A"]
    first, last = min(s["start"] for s in annual), max(s["end"] for s in annual)
    gui_model = build_gui_model(domain_model, period=last, first=first)

    # Clean the previous output but keep the installed frontend dependencies (npm install is slow)
    # and the npm lockfile (so everyone installs the same versions).
    keep = [out / "frontend" / "node_modules", out / "frontend" / "package-lock.json"]
    if out.exists():
        for path in sorted(out.rglob("*"), key=lambda p: -len(p.parts)):
            if any(path == k or k in path.parents for k in keep) or path.suffix == ".log":  # logs of a running app
                continue
            if path.is_dir():
                if not any(path.iterdir()):
                    path.rmdir()
            else:
                path.unlink()
    WebAppGenerator(model=domain_model, gui_model=gui_model, output_dir=str(out)).generate()
    backend = out / "backend"
    patch_generated_backend(backend)  # no-op with the patched BESSER; needed with PyPI 8.1.0

    # Defaults (WORLD, TOTAL, EXPORT, VALUE_IN_EUROS, A), totals, country patterns and the peer
    # comparison all come from the dimension roles detected at import (besser_sdmx.importer.roles);
    # only the focus and friendlier labels are specific to this app.
    insights = InsightsGenerator(
        domain_model, mapping, output_dir=str(backend),
        title="Luxembourg external trade in goods (Eurostat ds-045409)",
        focus=FOCUS,
        labels={"freq": "Frequency", "reporter": "Reporter", "partner": "Partner country",
                "product": "Product (HS/CN)", "flow": "Flow", "indicators": "Indicator"},
        base_threshold=0.01,
    )
    print("Insights API:", insights.generate())

    if _inside(out, APP.resolve()):
        print("\nDone. app/ was overwritten: check git diff before committing.")
    else:
        print(f"\nDone: {out}\nThe app you run (python run.py) is the hand-maintained app/, not this output.")


if __name__ == "__main__":
    main()

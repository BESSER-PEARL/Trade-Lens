"""GUI model of the Luxembourg Trade Explorer dashboard (BESSER B-UML).

Every chart is bound to the ``Observation`` class of the imported SDMX model and
reads from an analytics endpoint generated by ``besser_sdmx``'s InsightsGenerator
(``DataBinding.endpoint``). Layout, colours and typography are BESSER ``Styling``
objects on screens, containers and components, so the look is part of the model too.
Change it here and regenerate; never edit the generated React code.
"""
from besser.BUML.metamodel.gui import GUIModel, Module, Screen, Text, ViewContainer
from besser.BUML.metamodel.gui.binding import DataBinding
from besser.BUML.metamodel.gui.dashboard import BarChart, LineChart, MetricCard, Series
from besser.BUML.metamodel.gui.style import Color, Layout, LayoutType, Size, Styling

# Palette: STATEC-like navy, a clear blue for exports, slate for imports, Luxembourg red as accent.
NAVY, BLUE, SLATE, RED, TEAL = "#0b1f3a", "#1f6fd1", "#64748b", "#e4002b", "#0f9d8a"
PAGE_BG, CARD_BG, BORDER, MUTED, TEXT = "#f3f5f9", "#ffffff", "#e3e8ef", "#5b6678", "#14213d"
FONT = "Inter, 'Segoe UI', system-ui, -apple-system, sans-serif"
CARD_SHADOW = "0 1px 2px rgba(16, 24, 40, 0.06), 0 4px 16px rgba(16, 24, 40, 0.06)"


def _card(padding: str = "20px 22px") -> Styling:
    """A white rounded card with a soft shadow (charts and KPI cards)."""
    return Styling(
        size=Size(padding=padding, width="100%"),
        color=Color(background_color=CARD_BG, border=f"1px solid {BORDER}", border_radius="16px",
                    box_shadow=CARD_SHADOW, text_color=TEXT),
    )


def _row(columns: str, gap: str = "20px") -> Styling:
    """A CSS grid row: e.g. ``"1fr 1fr"`` for two equal columns."""
    return Styling(
        size=Size(width="100%"),
        layout=Layout(layout_type=LayoutType.GRID, grid_template_columns=columns, grid_gap=gap, gap=gap,
                      padding="0", margin="0"),
    )


def _text(name: str, content: str, order: float, size: str, weight: str = "600", color: str = TEXT,
          margin: str = "0") -> Text:
    return Text(name=name, content=content, display_order=order,
                styling=Styling(size=Size(font_size=size, font_weight=weight, margin=margin, line_height="1.3",
                                          font_family=FONT),
                                color=Color(text_color=color)))


def _section(name: str, title: str, order: float) -> Text:
    """A small uppercase section heading."""
    return Text(name=name, content=title, display_order=order,
                styling=Styling(size=Size(font_size="12px", font_weight="700", letter_spacing="0.08em",
                                          text_transform="uppercase", margin="8px 0 -4px 2px", font_family=FONT),
                                color=Color(text_color=MUTED)))


def _binding(observation, name: str, endpoint: str, label: str = "name", value: str = "value", aggregation=None):
    return DataBinding(
        domain_concept=observation,
        name=name,
        endpoint=endpoint,
        label_field_path=label,
        data_field_path=value,
        aggregation=aggregation,
    )


def _series(observation, name: str, label: str, endpoint: str, value: str = "value", x: str = "period",
            color: str = BLUE):
    return Series(name=name, label=label, data_binding=_binding(observation, f"{name}_binding", endpoint, x, value),
                  styling=Styling(color=Color(primary_color=color)))


def build_gui_model(domain_model, period: str = "2025", first: str = "2015") -> GUIModel:
    """``period``: the year the dashboard shows (the latest complete year loaded); ``first``: start of the trends."""
    obs = next(t for t in domain_model.types if getattr(t, "name", None) == "Observation")
    YEAR = period

    # ---- header banner -------------------------------------------------------------------
    header = ViewContainer(
        name="c00_header", description="Title banner", display_order=0,
        view_elements={
            _text("c00a_kicker", "STATEC Hackathon 2026  ·  Country × Good × Significance", 0, "12px", "700",
                  "rgba(255,255,255,0.75)", "0 0 8px 0"),
            _text("c00b_title", "Luxembourg's external trade in goods", 1, "32px", "800", "#ffffff"),
            _text("c00c_subtitle",
                  f"Eurostat ds-045409, {first}–{YEAR}, values in euros. Generated with BESSER from a class "
                  "diagram imported from the SDMX description of the data.", 2, "15px", "400",
                  "rgba(255,255,255,0.85)", "8px 0 0 0"),
        },
        styling=Styling(
            size=Size(width="100%"),
            color=Color(background_color=f"linear-gradient(120deg, {NAVY} 0%, #12346b 55%, {BLUE} 100%)",
                        border_radius="20px", border_bottom=f"4px solid {RED}",
                        box_shadow="0 8px 24px rgba(11, 31, 58, 0.25)"),
            layout=Layout(layout_type=LayoutType.FLEX, flex_direction="column", gap="0", padding="30px 36px",
                          margin="0"),
        ),
    )

    # ---- KPI cards -------------------------------------------------------------------------
    exports_card = MetricCard(name="c01_exports_card", metric_title=f"Exports {YEAR} (EUR)", format="compact",
                              show_trend=False, value_color=BLUE, value_size=34, display_order=0, styling=_card())
    exports_card.data_binding = _binding(obs, "exports_card_binding",
                                         f"/insights/series?flow=EXPORT&start={YEAR}&end={YEAR}", "period", "value", "sum")
    imports_card = MetricCard(name="c02_imports_card", metric_title=f"Imports {YEAR} (EUR)", format="compact",
                              show_trend=False, value_color=SLATE, value_size=34, display_order=1, styling=_card())
    imports_card.data_binding = _binding(obs, "imports_card_binding",
                                         f"/insights/series?flow=IMPORT&start={YEAR}&end={YEAR}", "period", "value", "sum")
    kpis = ViewContainer(name="c01_kpis", description="Headline figures", display_order=1,
                         view_elements={exports_card, imports_card}, styling=_row("1fr 1fr"))

    # ---- trend -----------------------------------------------------------------------------
    trend = LineChart(
        name="c03_trade_trend", title=f"Imports and exports, {first}–{YEAR} (EUR)", line_width=3,
        grid_color="#edf1f6", display_order=3, styling=_card(),
        series=[
            _series(obs, "imports", "Imports", f"/insights/series?flow=IMPORT&start={first}&end={YEAR}", color=SLATE),
            _series(obs, "exports", "Exports", f"/insights/series?flow=EXPORT&start={first}&end={YEAR}", color=BLUE),
        ],
    )

    # ---- partners --------------------------------------------------------------------------
    export_partners = BarChart(name="c04_export_partners", title=f"Export partners {YEAR}: share of total (%)",
                               orientation="horizontal", show_legend=False, grid_color="#edf1f6",
                               primary_color=BLUE, display_order=0, styling=_card())
    export_partners.data_binding = _binding(obs, "export_partners_binding",
                                            f"/insights/ranking/records?by=partner&period={YEAR}&flow=EXPORT", "name", "share")
    import_partners = BarChart(name="c05_import_partners", title=f"Import partners {YEAR}: share of total (%)",
                               orientation="horizontal", show_legend=False, grid_color="#edf1f6",
                               primary_color=SLATE, display_order=1, styling=_card())
    import_partners.data_binding = _binding(obs, "import_partners_binding",
                                            f"/insights/ranking/records?by=partner&period={YEAR}&flow=IMPORT", "name", "share")
    partners = ViewContainer(name="c05_partners", description="Partners", display_order=5,
                             view_elements={export_partners, import_partners}, styling=_row("1fr 1fr"))

    # ---- products --------------------------------------------------------------------------
    export_mix = BarChart(name="c06_export_mix", title=f"Exports {YEAR} by HS2 chapter: share of total (%)",
                          orientation="horizontal", show_legend=False, grid_color="#edf1f6", primary_color=BLUE,
                          display_order=0, styling=_card())
    export_mix.data_binding = _binding(obs, "export_mix_binding",
                                       f"/insights/ranking/records?by=product&period={YEAR}&flow=EXPORT&level=1&max_items=12",
                                       "name", "share")
    specialisation = BarChart(name="c07_specialisation", title=f"Where Luxembourg is specialised vs EU peers, {YEAR} (RCA)",
                              orientation="horizontal", show_legend=False, grid_color="#edf1f6", primary_color=TEAL,
                              display_order=1, styling=_card())
    specialisation.data_binding = _binding(obs, "specialisation_binding",
                                           f"/insights/specialisation/records?by=product&period={YEAR}&flow=EXPORT&limit=12",
                                           "name", "rca")
    products = ViewContainer(name="c07_products", description="Products", display_order=7,
                             view_elements={export_mix, specialisation}, styling=_row("1fr 1fr"))

    # ---- Luxembourg vs EU and seasonality ---------------------------------------------------
    # "How does Luxembourg's trade compare with that of other countries?" (the brief): export growth
    # of every EU reporting country since the first year, Luxembourg marked.
    peers = BarChart(name="c08_peers", title=f"Export growth {first}–{YEAR} (%), EU countries (Luxembourg ◀)",
                     orientation="horizontal", show_legend=False, grid_color="#edf1f6", primary_color=RED,
                     display_order=0, styling=_card())
    peers.data_binding = _binding(obs, "peers_binding",
                                  f"/insights/compare/records?by=reporter&period={YEAR}&flow=EXPORT&base={first}",
                                  "name", "growth")
    seasonal = LineChart(
        name="c09_seasonal_exports", title="Monthly exports: raw vs seasonally adjusted (EUR)", line_width=2,
        grid_color="#edf1f6", display_order=1, styling=_card(),
        series=[
            _series(obs, "exports_raw", "Raw", "/insights/series?flow=EXPORT&freq=M&adjust=true", "value",
                    color="#9fb3cc"),
            _series(obs, "exports_sa", "Seasonally adjusted", "/insights/series?flow=EXPORT&freq=M&adjust=true",
                    "adjusted", color=BLUE),
        ],
    )
    compare = ViewContainer(name="c09_compare", description="Luxembourg vs EU, seasonality", display_order=9,
                            view_elements={peers, seasonal}, styling=_row("1fr 1fr"))

    footer = _text("c10_footer",
                   "Source: Eurostat ds-045409 (EU trade since 1988 by HS2-4-6 and CN8), nominal euros; "
                   "latest months provisional. App generated by BESSER from B-UML models.",
                   10, "12px", "400", MUTED, "8px 0 0 2px")

    overview = Screen(
        name="Overview",
        description="Luxembourg's external trade at a glance",
        view_elements={
            header, kpis,
            _section("c02_s_trend", "Trend", 2), trend,
            _section("c04_s_partners", "Partners", 4), partners,
            _section("c06_s_products", "Products", 6), products,
            _section("c08_s_compare", "Luxembourg vs EU · Seasonality", 8), compare,
            footer,
        },
        is_main_page=True,
        route_path="/",
        screen_size="Large",
        styling=Styling(
            size=Size(max_width="1320px", font_family=FONT),
            color=Color(background_color=PAGE_BG, text_color=TEXT),
            layout=Layout(layout_type=LayoutType.FLEX, flex_direction="column", gap="20px", padding="28px 32px 40px",
                          margin="0 auto"),
        ),
    )
    return GUIModel(
        name="LuxTradeExplorer",
        package="lu.besser.trade",
        versionCode="1",
        versionName="0.1.0",
        description="Luxembourg Trade Explorer - STATEC Hackathon 2026",
        modules={Module(name="Main", screens={overview})},
    )

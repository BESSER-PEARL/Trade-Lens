"""The decision record of one specialist's answer: what the page shows under "How this was made" in the chat.

It goes to the page with the reply, as an extra field of the same WebSocket message (``what_happened``, next to
``action: agent_reply_str`` and ``message``, which stays the reply text): a page that does not read it shows the
reply as before. Plain-language fields come first, the exact queries last (``for_statisticians``).

    {"type": "what_happened", "version": 1, "agent": "trend_finder", "agent_title": "Trend finder",
     "question": "Why did exports jump in 2025?",
     "summary": "The trend finder ran 4 calculations, drew 3 things and checked 6 figures against them, in 14 s.",
     "plan": {"how": "...", "steps": [{"agent", "title", "why", "this_one", "asked"?}]},
     "methods": [{"name", "plain", "count"}],
     "calculations": [{"name", "about", "endpoint", "params", "url"}],
     "drawn": [{"what": "chart", "id", "type", "title", "method"} | {"what": "mark", "number", "kind", "label",
                "on", "on_title", "method"} | {"what": "title", "text"} | {"what": "page_year", "text"} | ...],
     "replaced": ["<chart title>"],
     "checked": {"in_reply", "verified", "corrected", "unmatched", "on_page", "words"},
     "time": {"seconds", "since_question"},
     "for_statisticians": {"plan_source", "task", "steps", "tools", "queries"}}
"""
from __future__ import annotations

import re
from typing import Any, Optional

from . import fmt, page
from . import methods as method_names

VERSION = 1

# Why each specialist is in a plan, in one plain line.
ROLE_WHY = {
    "trend_finder": "what changed, down to the product line, and lasting shifts",
    "cause_finder": "which dated events line up with the changes",
    "forecaster": "what comes next, with a band tested on the past",
    "visualizer": "the chart that shows it",
    "general": "a short answer, without a chart",
}
# How the plan was made, in plain words.
PLAN_HOW = {
    "llm": "The assistant's router (a small language model) chose who answers.",
    "rule": "A fixed rule for this kind of question chose who answers.",
    "keywords": "The question's words chose who answers (the router model was not reachable).",
    "owner": "The agent who drew the number you mention answers.",
    "direct": "Your own keep or remove, done at once, without a language model.",
    "no_trade": "Checked in the data first: Luxembourg did not trade these goods.",
}
CHART_WORDS = {"line": "line chart", "bar": "bar chart", "table": "table", "waterfall": "waterfall",
               "choropleth": "map", "flowmap": "map of partners", "heatmap": "grid", "treemap": "treemap",
               "butterfly": "butterfly chart", "bump": "rank chart", "scatter": "scatter chart", "text": "text",
               "flow": "crossroads", "compare": "comparison chart", "kpi": "figure"}
MARK_WORDS = {"thread": "thread", "trend": "trend line", "event": "event", "forecast": "forecast band",
              "annotation": "note", "highlight": "highlight", "trend_break": "trend break"}
_TECH_TASK = re.compile(r"[a-z]+_[a-z_]+|\(|=|\bget_|\bshow_panel\b")


def _title(role: str) -> str:
    from .specialists import TITLES
    return TITLES.get(role, role)


def _plural(n: int, one: str, many: Optional[str] = None) -> str:
    return f"{n} {one if n == 1 else (many or one + 's')}"


def _queries_of(item: dict) -> list[dict]:
    """The queries behind a panel or a mark: its own, and those of its facts."""
    out = list(item.get("queries") or [])
    if item.get("query"):
        out.append(item["query"])
    for f in (item.get("facts") or {}).values():
        if isinstance(f, dict) and f.get("endpoint"):
            out.append({"endpoint": f["endpoint"], "params": f.get("params") or {}})
    return out


def _method_name(item: dict, catalogue: Optional[dict], spec: Optional[dict] = None) -> Optional[str]:
    """The plain name of the method behind a panel or a mark (a mark without a query of its own: its chart's)."""
    qs = _queries_of(item)
    if not qs and spec and item.get("target"):
        target = page.panel(spec, item["target"])
        qs = _queries_of(target or {})
    names = []
    for q in qs:
        n = method_names.method_of(q.get("endpoint", ""), catalogue, q.get("params") or {})["name"]
        if n not in names:
            names.append(n)
    return " and ".join(names[:2]) or None


_FLOWS = {"EXPORT": "exports", "IMPORT": "imports", "2": "exports", "1": "imports"}
_BY = {"partner": "by partner country", "product": "by product", "reporter": "by EU country"}
_FORECAST = {"nn": "the neural network generated by BESSER", "ets": "Holt-Winters", "theta": "the Theta method",
             "gbm": "gradient boosting", "snaive": "the seasonal naive forecast", "ensemble": "the default ensemble"}


def about(endpoint: str, p: dict, names: Optional[dict] = None) -> str:
    """What one calculation was run on, in plain words: 'exports by product, 2024 to 2025, inside electrical
    machinery'."""
    from agents.kit.view import COUNTRY_NAMES, HS_SHORT
    names = names or {}

    def goods(code: str) -> str:
        code = str(code)
        n = names.get(code) or HS_SHORT.get(code)
        return n[:1].lower() + n[1:] if n and not n[:2].isupper() else (n or f"product {code}")

    bits = []
    flows = [_FLOWS.get(f.strip().upper(), f.strip().lower()) for f in str(p.get("flow") or "").split(",") if f.strip()]
    word = " and ".join(dict.fromkeys(flows)) or ("imports and exports" if endpoint == "/insights/flows" else "")
    if p.get("freq") == "M":
        word = ("monthly " + word).strip()
    if p.get("by") in _BY:
        word = (word + " " + _BY[p["by"]]).strip()
    if word:
        bits.append(word)
    if p.get("previous") and p.get("period"):
        bits.append(f"{p['previous']} to {p['period']}")
    elif p.get("period"):
        bits.append(str(p["period"]))
    elif p.get("start") and p.get("end") and p["start"] != p["end"]:
        bits.append(f"{p['start']} to {p['end']}")
    elif p.get("start") and p.get("end"):
        bits.append(str(p["start"]))
    elif p.get("start"):
        bits.append(f"from {p['start']}")
    if p.get("product") and str(p["product"]).upper() != "TOTAL":
        bits.append(", ".join(goods(c) for c in str(p["product"]).split(",")))
    if p.get("parent"):
        bits.append(f"inside {goods(p['parent'])}")
    if p.get("partner") and str(p["partner"]).upper() != "WORLD":
        bits.append("with " + ", ".join(COUNTRY_NAMES.get(c.strip().upper(), c.strip())
                                        for c in str(p["partner"]).split(",")))
    if str(p.get("adjust")).lower() == "true":
        bits.append("seasonally adjusted")
    if endpoint == "/insights/forecast":
        m = str(p.get("method") or "auto")
        bits.append(f"{p.get('horizon', 12)} months ahead" + (f", by {_FORECAST[m]}" if m in _FORECAST else ""))
        if str(p.get("backtest")).lower() == "true":
            bits.append("every method tested")
    if endpoint == "/product/search/" and p.get("label"):
        bits.append(f"\"{p['label']}\"")
    return ", ".join(bits)


def _calculations(sources: list[str], catalogue: Optional[dict],
                  names: Optional[dict] = None) -> tuple[list[dict], list[dict]]:
    """(the methods used, each once with its plain sentence and how many times; each calculation run)."""
    out, used, seen = [], {}, set()
    for url in sources:
        if url in seen:
            continue
        seen.add(url)
        m = method_names.method_of(url, catalogue)
        row = {"name": m["name"], "about": about(m["endpoint"], m["params"], names), "endpoint": m["endpoint"],
               "params": m["params"], "url": url}
        if m.get("no_calculation"):
            row["no_calculation"] = True
        out.append(row)
        if m["name"] not in used:
            used[m["name"]] = {"name": m["name"], "plain": m["plain"], "count": 0,
                               **({"no_calculation": True} if m.get("no_calculation") else {})}
        used[m["name"]]["count"] += 1
    return list(used.values()), out


def _drawn(turn: Any, spec: Optional[dict], catalogue: Optional[dict]) -> list[dict]:
    out: list[dict] = []
    if "set_title" in (turn.done or []) and spec:
        out.append({"what": "title", "text": spec.get("title")})
    if "set_context" in (turn.done or []) and spec:
        ctx = spec.get("context") or {}
        out.append({"what": "page_year", "text": f"moved the page to {ctx.get('period')}"})
    by_id = {p["id"]: p for p in (spec or {}).get("panels", [])}
    for pid in turn.panels or []:
        p = by_id.get(pid)
        if p is None:   # drawn, then replaced in the same turn
            continue
        chart = "the 'In short' headline" if pid == "headline" else CHART_WORDS.get(p["type"], p["type"])
        out.append({"what": "chart", "id": pid, "type": p["type"], "chart": chart,
                    "title": p.get("title"), "method": _method_name(p, catalogue)})
    marks = {m["id"]: m for m in (spec or {}).get("marks", [])}
    for mid in turn.marks or []:
        m = marks.get(mid)
        if m is None:
            continue
        on = by_id.get(m["target"]) or {}
        nums = page.page_numbers(spec, [mid]) if spec else []
        out.append({"what": "mark", "number": nums[0] if nums else None, "kind": m["kind"],
                    "mark": MARK_WORDS.get(m["kind"], m["kind"]), "label": (m.get("params") or {}).get("label"),
                    "on": m["target"], "on_title": on.get("title"), "method": _method_name(m, catalogue, spec)})
    if turn.removed:
        out.append({"what": "removed", "numbers": list(turn.removed)})
    if turn.cleared is not None:
        out.append({"what": "cleared", "kept": turn.cleared.get("kept"), "pinned": turn.cleared.get("pinned")})
    return out


def _facts_on_page(turn: Any, spec: Optional[dict]) -> int:
    """How many figures the marks and charts of this turn show, each filled by the page from a calculation."""
    if not spec:
        return 0
    n = 0
    for p in spec.get("panels", []):
        if p["id"] in (turn.panels or []):
            n += len(p.get("facts") or {})
    for m in spec.get("marks", []):
        if m["id"] in (turn.marks or []):
            n += len(m.get("facts") or {})
    return n


def checked(text: str, unverified: list[str], corrected: list[str], on_page: int) -> dict:
    """The figures of the reply checked against what the calculations returned in this turn; ranks ('fourth',
    '13th') count as figures, checked against the rankings the turn read."""
    from .specialists import ranks_in
    ranks = len(ranks_in(text or ""))
    in_reply = len(fmt.figures_in(text or "")) + ranks
    unmatched = len(unverified or [])
    verified = max(0, in_reply - unmatched)
    words = (f"{_plural(verified, 'figure')} in the reply checked against the calculations"
             + (f" ({_plural(ranks, 'rank')} among them)" if ranks else "")
             if in_reply else "No figure in the reply")
    if corrected:
        words += f"; {_plural(len(corrected), 'figure')} of a first draft sent back and rewritten"
    if unmatched:
        words += f"; {unmatched} not matched"
    if on_page:
        words += f". {_plural(on_page, 'figure')} on the page, each filled in from a calculation, never typed"
    return {"in_reply": in_reply, "verified": verified, "corrected": len(corrected or []), "unmatched": unmatched,
            "ranks": ranks, "on_page": on_page, "words": words + "."}


def build(*, question: str, role: str, reply: Any, turn: Any, plan_steps: list[tuple[str, str]],
          plan_source: str, catalogue: Optional[dict] = None, since_question: Optional[float] = None,
          names: Optional[dict] = None) -> dict:
    """The decision record of one specialist's answer (see the module docstring for the format)."""
    spec = turn.spec
    title = _title(role)
    steps = []
    for agent, task in plan_steps:
        step = {"agent": agent, "title": _title(agent), "why": ROLE_WHY.get(agent, ""), "this_one": agent == role}
        if task and not _TECH_TASK.search(task) and ":" not in task[:12]:
            step["asked"] = task
        steps.append(step)
    used, calcs = _calculations(list(reply.sources or turn.sources or []), catalogue, names)
    drawn = _drawn(turn, spec, catalogue)
    things = [d for d in drawn if d["what"] in ("chart", "mark", "title", "page_year")]
    check = checked(reply.text, reply.unverified, getattr(reply, "corrected", []), _facts_on_page(turn, spec))
    n_calc = sum(1 for c in calcs if not c.get("no_calculation"))
    secs = getattr(reply, "seconds", 0.0) or 0.0
    parts = [f"ran {_plural(n_calc, 'calculation')}" if n_calc else "ran no calculation",
             f"drew {_plural(len(things), 'thing')}" if things else "drew nothing"]
    summary = (f"The {title.lower()} ({ROLE_WHY.get(role, 'the answer')}) " + ", ".join(parts)
               + (f" and checked {_plural(check['verified'], 'figure')} against the calculations"
                  if check["in_reply"] else "") + (f", in {secs:.0f} s" if secs else "") + ".")
    tools = []
    for a in turn.done or []:
        if a not in tools:
            tools.append(a)
    return {
        "type": "what_happened",
        "version": VERSION,
        "agent": role,
        "agent_title": title,
        "question": question,
        "summary": summary,
        "plan": {"how": PLAN_HOW.get(plan_source, PLAN_HOW["llm"]), "steps": steps},
        "methods": used,
        "calculations": calcs,
        "drawn": drawn,
        "replaced": [r.get("title") for r in turn.replaced or [] if r.get("title")],
        "checked": check,
        "time": {"seconds": round(secs, 1), "since_question": round(since_question, 1) if since_question else None},
        "for_statisticians": {
            "plan_source": plan_source,
            "task": next((t for a, t in plan_steps if a == role), ""),
            "steps": getattr(reply, "steps", 0),
            "tools": tools,
            "refused": list(turn.refused or []),
            "queries": [c["url"] for c in calcs],
            "page_version": getattr(reply, "version", None),
        },
    }

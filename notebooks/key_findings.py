from __future__ import annotations

import sqlite3
from pathlib import Path

import pandas as pd
from statsmodels.tsa.seasonal import STL

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "lux_trade.db"
OUT = ROOT / "docs" / "findings.md"
YEAR, PREV, FIRST = "2025", "2024", "2015"
EU_PEERS = ["AT", "BE", "BG", "CY", "CZ", "DE", "DK", "EE", "ES", "FI", "FR", "GR", "HR", "HU", "IE", "IT",
            "LT", "LV", "MT", "NL", "PL", "PT", "RO", "SE", "SI", "SK"]
con = sqlite3.connect(DB)


def q(sql: str, **params) -> pd.DataFrame:
    return pd.read_sql_query(sql, con, params=params)


def label(text: str) -> str:
    text = text.split(" (incl.")[0]
    letters = [c for c in text if c.isalpha()]
    if letters and sum(c.isupper() for c in letters) / len(letters) > 0.8:
        text = text[:1].upper() + text[1:].lower()
    return text if len(text) < 70 else text[:67] + "..."


def bn(v: float) -> str:
    return f"{'-' if v < 0 else ''}€{abs(v) / 1e9:.2f} bn"


def pct(s: float) -> str:
    return f"{100 * s:.1f}%" if s >= 0.01 else f"{100 * s:.2g}%"


def hhi_reading(hhi: float) -> str:
    """Usual competition-authority bands for the Herfindahl-Hirschman index (0-10,000)."""
    if hhi < 1500:
        return "below 1,500, the usual threshold for concentration"
    if hhi <= 2500:
        return "moderately concentrated (1,500-2,500)"
    return "highly concentrated (above 2,500)"


BASE = "o.freq='A' AND o.reporter_id='LU' AND o.indicators='VALUE_IN_EUROS'"
lines: list[str] = ["# Key findings: Luxembourg's external trade in goods", "",
                    f"Generated by `notebooks/key_findings.py` from Eurostat ds-045409 (values in nominal euros).", ""]

# %% 1. Totals and balance
tot = q(f"""SELECT o.time_period AS year, o.flow, o.obs_value AS v FROM observation o
            WHERE {BASE} AND o.partner_id='WORLD' AND o.product_id='TOTAL' AND o.time_period BETWEEN :a AND :b""",
        a=FIRST, b=YEAR).pivot(index="year", columns="flow", values="v")
tot["balance"] = tot["EXPORT"] - tot["IMPORT"]
e, i = tot.loc[YEAR, "EXPORT"], tot.loc[YEAR, "IMPORT"]
lines += ["## 1. A structural deficit of about €9 bn", "",
          f"In {YEAR} Luxembourg exported {bn(e)} and imported {bn(i)} of goods, a deficit of {bn(i - e)}. "
          f"Imports have exceeded exports every year since {FIRST}. "
          f"Exports grew {pct(e / tot.loc[PREV, 'EXPORT'] - 1)} on {PREV}.", "",
          "| Year | Exports | Imports | Balance |", "| --- | --- | --- | --- |"]
lines += [f"| {y} | {bn(r.EXPORT)} | {bn(r.IMPORT)} | {bn(r.balance)} |" for y, r in tot.iterrows()]

# %% 2. Concentration on partners
part = q(f"""SELECT o.flow, o.partner_id AS code, c.label, o.obs_value AS v FROM observation o
             JOIN country c ON c.code=o.partner_id
             WHERE {BASE} AND o.product_id='TOTAL' AND o.time_period=:y AND length(o.partner_id)=2
               AND o.partner_id NOT LIKE 'Q%'""", y=YEAR)
lines += ["", "## 2. Three neighbours dominate", ""]
for flow, word in (("EXPORT", "exports"), ("IMPORT", "imports")):
    p = part[part.flow == flow].sort_values("v", ascending=False)
    total = e if flow == "EXPORT" else i
    shares = p.v / total
    hhi = (shares ** 2).sum() * 10_000
    top3 = ", ".join(f"{label(r.label)} {pct(r.v / total)}" for r in p.head(3).itertuples())
    lines.append(f"- **{word.capitalize()}:** the top 3 partners take {pct(shares.head(3).sum())} ({top3}). "
                 f"Herfindahl index {hhi:,.0f}: {hhi_reading(hhi)}.")

# %% 3. The significance ladder
prod = q(f"""SELECT o.product_id AS code, p.level, o.obs_value AS v FROM observation o
             JOIN product p ON p.code=o.product_id
             WHERE {BASE} AND o.flow='EXPORT' AND o.partner_id='WORLD' AND o.time_period=:y AND p.level BETWEEN 1 AND 4""",
         y=YEAR)
lines += ["", f"## 3. The significance ladder ({YEAR} exports)", "",
          "A fixed cutoff fails across levels of detail; one decimal per level keeps about 90% of value in view.", "",
          "| Level | Codes with trade | ≥ 1% | ≥ 0.1% | ≥ 0.01% | ≥ 0.001% | Ladder cutoff | Coverage at cutoff |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"]
names = {1: "HS2", 2: "HS4", 3: "HS6", 4: "CN8"}
for lvl in (1, 2, 3, 4):
    s = prod[(prod.level == lvl) & (prod.v > 0)].v / e
    cells = [f"{(s >= t).sum()} ({pct(s[s >= t].sum())})" for t in (0.01, 0.001, 0.0001, 0.00001)]
    cut = 0.01 / 10 ** (lvl - 1)
    lines.append(f"| {names[lvl]} | {len(s):,} | " + " | ".join(cells) + f" | {pct(cut)} | {pct(s[s >= cut].sum())} |")

# %% 4. Movers
hs2 = q(f"""SELECT o.product_id AS code, p.label, o.time_period AS y, o.obs_value AS v FROM observation o
            JOIN product p ON p.code=o.product_id
            WHERE {BASE} AND o.flow='EXPORT' AND o.partner_id='WORLD' AND p.level=1 AND o.time_period IN (:a, :b)""",
        a=PREV, b=YEAR).pivot_table(index=["code", "label"], columns="y", values="v", fill_value=0).reset_index()
hs2["change"] = hs2[YEAR] - hs2[PREV]
lines += ["", f"## 4. What moved between {PREV} and {YEAR} (exports, HS2)", ""]
for r in hs2.sort_values("change", ascending=False).head(3).itertuples():
    lines.append(f"- ▲ {r.code} {label(r.label)}: {bn(getattr(r, '_3'))} → {bn(getattr(r, '_4'))} ({'+' if r.change >= 0 else ''}{bn(r.change)})")
for r in hs2.sort_values("change").head(3).itertuples():
    lines.append(f"- ▼ {r.code} {label(r.label)}: {bn(getattr(r, '_3'))} → {bn(getattr(r, '_4'))} ({bn(r.change)})")

# %% 5. Specialisation vs EU peers (revealed comparative advantage)
eu = q(f"""SELECT o.reporter_id AS rep, o.product_id AS code, o.obs_value AS v FROM observation o
           JOIN product p ON p.code=o.product_id
           WHERE o.freq='A' AND o.indicators='VALUE_IN_EUROS' AND o.flow='EXPORT' AND o.partner_id='WORLD'
             AND p.level=1 AND o.time_period=:y""", y=YEAR)
lu = eu[eu.rep == "LU"].set_index("code").v
peers = eu[eu.rep.isin(EU_PEERS)].groupby("code").v.sum()
rca = ((lu / lu.sum()) / (peers / peers.sum())).dropna().sort_values(ascending=False)
labels = q("SELECT code, label FROM product WHERE level=1").set_index("code").label
lines += ["", f"## 5. Where Luxembourg is specialised ({YEAR}, exports vs 26 EU peers)", "",
          "Revealed comparative advantage = LU share of a chapter in its exports ÷ the peers' share. Above 1 = specialised.", "",
          "| Chapter | RCA | LU exports |", "| --- | --- | --- |"]
lines += [f"| {c} {label(labels.get(c, c))} | {v:.1f} | {bn(lu[c])} |" for c, v in rca.head(8).items()]

# %% 6. Seasonality
m = q(f"""SELECT o.time_period AS period, o.obs_value AS v FROM observation o
          WHERE o.freq='M' AND o.reporter_id='LU' AND o.indicators='VALUE_IN_EUROS' AND o.flow='EXPORT'
            AND o.partner_id='WORLD' AND o.product_id='TOTAL' ORDER BY o.time_period""")
res = STL(m.v.reset_index(drop=True), period=12, robust=True).fit()
m["seasonal"] = res.seasonal.values
m["month"] = m.period.str[5:7]
by_month = m.groupby("month").seasonal.mean()
lines += ["", "## 6. Seasonality", "",
          f"Monthly exports {m.period.iloc[0]}–{m.period.iloc[-1]}, STL decomposition: the weakest month is "
          f"{by_month.idxmin()} ({bn(-by_month.min())} below trend on average; the summer break is a likely "
          f"explanation, not something the data shows) and the strongest "
          f"is {by_month.idxmax()} ({'+' if by_month.max() >= 0 else ''}{bn(by_month.max())}). "
          f"Months of {m.period.iloc[-1][:4]} are provisional and will be revised, and STL estimates are least "
          "stable at the ends of the series. "
          "The Explorer shows the seasonally adjusted series for the world total, each chapter and each "
          "partner's total (the monthly data loaded)."]

# %% 7. New and fast-growing niches (CN8)
cn8 = q(f"""SELECT o.product_id AS code, p.label, o.time_period AS y, o.obs_value AS v FROM observation o
            JOIN product p ON p.code=o.product_id
            WHERE {BASE} AND o.flow='EXPORT' AND o.partner_id='WORLD' AND p.level=4 AND o.time_period IN (:a, :b)""",
        a=PREV, b=YEAR).pivot_table(index=["code", "label"], columns="y", values="v", fill_value=0).reset_index()
new = cn8[(cn8[PREV] == 0) & (cn8[YEAR] / e >= 0.00001)].sort_values(YEAR, ascending=False)
# Growth from a meaningful base only (≥ 0.001% of exports the year before), or ratios explode.
fast = cn8[(cn8[PREV] / tot.loc[PREV, "EXPORT"] >= 0.00001) & (cn8[YEAR] / e >= 0.0001)].assign(
    g=lambda d: d[YEAR] / d[PREV] - 1)
fast = fast.sort_values("g", ascending=False)
lines += ["", "## 7. Signals in the long tail (CN8, below any top-10 chart)", "",
          f"- {len(new)} CN8 products were exported in {YEAR} but not in {PREV} (each ≥ 0.001% of exports)."]
lines += [f"  - {r.code} {label(r.label)}: {bn(getattr(r, '_4'))}" for r in new.head(3).itertuples()]
lines += ["- Fastest growing products (≥ 0.01% of exports now, ≥ 0.001% a year before):"]
lines += [f"  - {r.code} {label(r.label)}: ×{r.g + 1:.1f} (€{getattr(r, '_3') / 1e6:.1f} m → €{getattr(r, '_4') / 1e6:.1f} m)"
          for r in fast.head(3).itertuples()]

# %%
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Wrote {OUT}")
